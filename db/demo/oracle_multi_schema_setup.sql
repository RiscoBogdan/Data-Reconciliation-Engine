-- Multi-schema Oracle demo setup
-- Creates 2 additional Oracle schemas/users and seeds each with DEMO_* tables.
-- Requested schema names: ORACLE_SCHEMA1 and ORACLE_SCHEMA2.
--
-- Run as a privileged user (SYS/SYSTEM) in SQL*Plus/SQLcl.
-- Adjust passwords/tablespace as needed for your environment.

-- 1) Ensure schemas/users exist
BEGIN
    EXECUTE IMMEDIATE 'CREATE USER ORACLE_SCHEMA1 IDENTIFIED BY "oracle_schema1"';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -01920 AND SQLCODE != -01921 THEN RAISE; END IF;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'CREATE USER ORACLE_SCHEMA2 IDENTIFIED BY "oracle_schema2"';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -01920 AND SQLCODE != -01921 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO ORACLE_SCHEMA1';
    EXECUTE IMMEDIATE 'GRANT UNLIMITED TABLESPACE TO ORACLE_SCHEMA1';
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO ORACLE_SCHEMA2';
    EXECUTE IMMEDIATE 'GRANT UNLIMITED TABLESPACE TO ORACLE_SCHEMA2';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -01919 THEN RAISE; END IF;
END;
/

-- 2) Build/seed ORACLE_SCHEMA1
