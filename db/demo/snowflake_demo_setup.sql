-- Demo destination dataset for Snowflake (database: RECON_DB, schema: PUBLIC)
-- Mirrors Oracle demo tables with intentional data differences.

USE DATABASE RECON_DB;
USE SCHEMA PUBLIC;

DROP TABLE IF EXISTS DEMO_INVENTORY;
DROP TABLE IF EXISTS DEMO_PAYMENTS;
DROP TABLE IF EXISTS DEMO_ORDERS;
DROP TABLE IF EXISTS DEMO_PRODUCTS;
DROP TABLE IF EXISTS DEMO_CUSTOMERS;

CREATE TABLE DEMO_CUSTOMERS (
    CUSTOMER_ID      NUMBER(12,0)      NOT NULL,
    FULL_NAME        STRING            NOT NULL,
    EMAIL            STRING,
    COUNTRY_CODE     STRING,
    LAST_UPDATED_TS  TIMESTAMP_NTZ     NOT NULL,
    CONSTRAINT PK_DEMO_CUSTOMERS PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE DEMO_PRODUCTS (
    PRODUCT_ID       NUMBER(12,0)      NOT NULL,
    PRODUCT_NAME     STRING            NOT NULL,
    CATEGORY         STRING,
    PRICE            NUMBER(12,2),
    LAST_UPDATED_TS  TIMESTAMP_NTZ     NOT NULL,
    CONSTRAINT PK_DEMO_PRODUCTS PRIMARY KEY (PRODUCT_ID)
);

CREATE TABLE DEMO_ORDERS (
    ORDER_ID         NUMBER(12,0)      NOT NULL,
    LINE_ID          NUMBER(4,0)       NOT NULL,
    CUSTOMER_ID      NUMBER(12,0)      NOT NULL,
    PRODUCT_ID       NUMBER(12,0)      NOT NULL,
    QUANTITY         NUMBER(10,2),
    ORDER_STATUS     STRING,
    LAST_UPDATED_TS  TIMESTAMP_NTZ     NOT NULL,
    CONSTRAINT PK_DEMO_ORDERS PRIMARY KEY (ORDER_ID, LINE_ID)
);

CREATE TABLE DEMO_PAYMENTS (
    PAYMENT_ID       NUMBER(12,0)      NOT NULL,
    ORDER_ID         NUMBER(12,0)      NOT NULL,
    PAYMENT_METHOD   STRING,
    AMOUNT           NUMBER(12,2),
    PAYMENT_TS       TIMESTAMP_NTZ,
    LAST_UPDATED_TS  TIMESTAMP_NTZ     NOT NULL,
    CONSTRAINT PK_DEMO_PAYMENTS PRIMARY KEY (PAYMENT_ID)
);

CREATE TABLE DEMO_INVENTORY (
    WAREHOUSE_ID     NUMBER(6,0)       NOT NULL,
    PRODUCT_ID       NUMBER(12,0)      NOT NULL,
    ON_HAND_QTY      NUMBER(12,2),
    RESERVED_QTY     NUMBER(12,2),
    LAST_UPDATED_TS  TIMESTAMP_NTZ     NOT NULL,
    CONSTRAINT PK_DEMO_INVENTORY PRIMARY KEY (WAREHOUSE_ID, PRODUCT_ID)
);

