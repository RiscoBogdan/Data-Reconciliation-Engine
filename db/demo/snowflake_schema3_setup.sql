-- Snowflake companion setup for ORACLE_SCHEMA3 custom tables.
-- Creates matching 3 tables with intentional value differences for reconciliation.

USE DATABASE RECON_DB;
USE SCHEMA PUBLIC;

DROP TABLE IF EXISTS SC3_SHIPMENT_TRACK;
DROP TABLE IF EXISTS SC3_INVOICE_HEADER;
DROP TABLE IF EXISTS SC3_CLIENT_PROFILE;

CREATE TABLE SC3_CLIENT_PROFILE (
    CLIENT_ID         NUMBER(12,0)     NOT NULL,
    CLIENT_NAME       STRING           NOT NULL,
    TIER_CODE         STRING,
    COUNTRY_CODE      STRING,
    LAST_UPDATED_TS   TIMESTAMP_NTZ    NOT NULL,
    CONSTRAINT PK_SC3_CLIENT_PROFILE PRIMARY KEY (CLIENT_ID)
);

CREATE TABLE SC3_INVOICE_HEADER (
    INVOICE_ID        NUMBER(12,0)     NOT NULL,
    CLIENT_ID         NUMBER(12,0)     NOT NULL,
    INVOICE_STATUS    STRING,
    TOTAL_AMOUNT      NUMBER(12,2),
    CURRENCY_CODE     STRING,
    LAST_UPDATED_TS   TIMESTAMP_NTZ    NOT NULL,
    CONSTRAINT PK_SC3_INVOICE_HEADER PRIMARY KEY (INVOICE_ID)
);

CREATE TABLE SC3_SHIPMENT_TRACK (
    SHIPMENT_ID       NUMBER(12,0)     NOT NULL,
    INVOICE_ID        NUMBER(12,0)     NOT NULL,
    CARRIER_NAME      STRING,
    TRACKING_STATE    STRING,
    SHIPPED_TS        TIMESTAMP_NTZ,
    LAST_UPDATED_TS   TIMESTAMP_NTZ    NOT NULL,
    CONSTRAINT PK_SC3_SHIPMENT_TRACK PRIMARY KEY (SHIPMENT_ID)
);

