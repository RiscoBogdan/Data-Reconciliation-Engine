-- Oracle demo setup for a third schema with different table names.
-- Creates ORACLE_SCHEMA3 and seeds 3 unique tables.
-- Run as SYS/SYSTEM in the target PDB (e.g., FREEPDB1).

BEGIN
    EXECUTE IMMEDIATE 'CREATE USER ORACLE_SCHEMA3 IDENTIFIED BY "oracle_schema3"';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -01920 AND SQLCODE != -01921 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO ORACLE_SCHEMA3';
    EXECUTE IMMEDIATE 'GRANT UNLIMITED TABLESPACE TO ORACLE_SCHEMA3';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -01919 THEN RAISE; END IF;
END;
/

ALTER SESSION SET CURRENT_SCHEMA = ORACLE_SCHEMA3;

BEGIN EXECUTE IMMEDIATE 'DROP TABLE SC3_SHIPMENT_TRACK PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE SC3_INVOICE_HEADER PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE SC3_CLIENT_PROFILE PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/

CREATE TABLE SC3_CLIENT_PROFILE (
    CLIENT_ID         NUMBER(12)      NOT NULL,
    CLIENT_NAME       VARCHAR2(120)   NOT NULL,
    TIER_CODE         VARCHAR2(20),
    COUNTRY_CODE      VARCHAR2(3),
    LAST_UPDATED_TS   TIMESTAMP       NOT NULL,
    CONSTRAINT PK_SC3_CLIENT_PROFILE PRIMARY KEY (CLIENT_ID)
);

CREATE TABLE SC3_INVOICE_HEADER (
    INVOICE_ID        NUMBER(12)      NOT NULL,
    CLIENT_ID         NUMBER(12)      NOT NULL,
    INVOICE_STATUS    VARCHAR2(30),
    TOTAL_AMOUNT      NUMBER(12,2),
    CURRENCY_CODE     VARCHAR2(3),
    LAST_UPDATED_TS   TIMESTAMP       NOT NULL,
    CONSTRAINT PK_SC3_INVOICE_HEADER PRIMARY KEY (INVOICE_ID)
);

CREATE TABLE SC3_SHIPMENT_TRACK (
    SHIPMENT_ID       NUMBER(12)      NOT NULL,
    INVOICE_ID        NUMBER(12)      NOT NULL,
    CARRIER_NAME      VARCHAR2(60),
    TRACKING_STATE    VARCHAR2(30),
    SHIPPED_TS        TIMESTAMP,
    LAST_UPDATED_TS   TIMESTAMP       NOT NULL,
    CONSTRAINT PK_SC3_SHIPMENT_TRACK PRIMARY KEY (SHIPMENT_ID)
);

