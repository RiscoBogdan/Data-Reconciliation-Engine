-- Migration helper: copy demo data from ORACLE_SCHEM2 to ORACLE_SCHEMA2.
-- Use when older setup created ORACLE_SCHEM2 and you want standardized ORACLE_SCHEMA2.
-- Run as SYS/SYSTEM.

BEGIN
    EXECUTE IMMEDIATE 'CREATE USER ORACLE_SCHEMA2 IDENTIFIED BY "oracle_schema2"';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -01920 AND SQLCODE != -01921 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE SEQUENCE, CREATE PROCEDURE TO ORACLE_SCHEMA2';
    EXECUTE IMMEDIATE 'GRANT UNLIMITED TABLESPACE TO ORACLE_SCHEMA2';
EXCEPTION WHEN OTHERS THEN
    IF SQLCODE != -01919 THEN RAISE; END IF;
END;
/

BEGIN EXECUTE IMMEDIATE 'DROP TABLE ORACLE_SCHEMA2.DEMO_INVENTORY PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE ORACLE_SCHEMA2.DEMO_PAYMENTS PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE ORACLE_SCHEMA2.DEMO_ORDERS PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE ORACLE_SCHEMA2.DEMO_PRODUCTS PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP TABLE ORACLE_SCHEMA2.DEMO_CUSTOMERS PURGE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF; END;
/

CREATE TABLE ORACLE_SCHEMA2.DEMO_CUSTOMERS AS SELECT * FROM ORACLE_SCHEM2.DEMO_CUSTOMERS;
ALTER TABLE ORACLE_SCHEMA2.DEMO_CUSTOMERS ADD CONSTRAINT PK_DEMO_CUSTOMERS PRIMARY KEY (CUSTOMER_ID);

CREATE TABLE ORACLE_SCHEMA2.DEMO_PRODUCTS AS SELECT * FROM ORACLE_SCHEM2.DEMO_PRODUCTS;
ALTER TABLE ORACLE_SCHEMA2.DEMO_PRODUCTS ADD CONSTRAINT PK_DEMO_PRODUCTS PRIMARY KEY (PRODUCT_ID);

CREATE TABLE ORACLE_SCHEMA2.DEMO_ORDERS AS SELECT * FROM ORACLE_SCHEM2.DEMO_ORDERS;
ALTER TABLE ORACLE_SCHEMA2.DEMO_ORDERS ADD CONSTRAINT PK_DEMO_ORDERS PRIMARY KEY (ORDER_ID, LINE_ID);

CREATE TABLE ORACLE_SCHEMA2.DEMO_PAYMENTS AS SELECT * FROM ORACLE_SCHEM2.DEMO_PAYMENTS;
ALTER TABLE ORACLE_SCHEMA2.DEMO_PAYMENTS ADD CONSTRAINT PK_DEMO_PAYMENTS PRIMARY KEY (PAYMENT_ID);

CREATE TABLE ORACLE_SCHEMA2.DEMO_INVENTORY AS SELECT * FROM ORACLE_SCHEM2.DEMO_INVENTORY;
ALTER TABLE ORACLE_SCHEMA2.DEMO_INVENTORY ADD CONSTRAINT PK_DEMO_INVENTORY PRIMARY KEY (WAREHOUSE_ID, PRODUCT_ID);

GRANT SELECT ON ORACLE_SCHEMA2.DEMO_CUSTOMERS TO RECON;
GRANT SELECT ON ORACLE_SCHEMA2.DEMO_PRODUCTS TO RECON;
GRANT SELECT ON ORACLE_SCHEMA2.DEMO_ORDERS TO RECON;
GRANT SELECT ON ORACLE_SCHEMA2.DEMO_PAYMENTS TO RECON;
GRANT SELECT ON ORACLE_SCHEMA2.DEMO_INVENTORY TO RECON;

COMMIT;

