CREATE TABLE DEMO_CUSTOMERS (
    CUSTOMER_ID      NUMBER(12)      NOT NULL,
    FULL_NAME        VARCHAR2(100)   NOT NULL,
    EMAIL            VARCHAR2(200),
    COUNTRY_CODE     VARCHAR2(3),
    LAST_UPDATED_TS  TIMESTAMP       NOT NULL,
    CONSTRAINT PK_DEMO_CUSTOMERS PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE DEMO_PRODUCTS (
    PRODUCT_ID       NUMBER(12)      NOT NULL,
    PRODUCT_NAME     VARCHAR2(120)   NOT NULL,
    CATEGORY         VARCHAR2(60),
    PRICE            NUMBER(12,2),
    LAST_UPDATED_TS  TIMESTAMP       NOT NULL,
    CONSTRAINT PK_DEMO_PRODUCTS PRIMARY KEY (PRODUCT_ID)
);

CREATE TABLE DEMO_ORDERS (
    ORDER_ID         NUMBER(12)      NOT NULL,
    LINE_ID          NUMBER(4)       NOT NULL,
    CUSTOMER_ID      NUMBER(12)      NOT NULL,
    PRODUCT_ID       NUMBER(12)      NOT NULL,
    QUANTITY         NUMBER(10,2),
    ORDER_STATUS     VARCHAR2(30),
    LAST_UPDATED_TS  TIMESTAMP       NOT NULL,
    CONSTRAINT PK_DEMO_ORDERS PRIMARY KEY (ORDER_ID, LINE_ID)
);

CREATE TABLE DEMO_PAYMENTS (
    PAYMENT_ID       NUMBER(12)      NOT NULL,
    ORDER_ID         NUMBER(12)      NOT NULL,
    PAYMENT_METHOD   VARCHAR2(40),
    AMOUNT           NUMBER(12,2),
    PAYMENT_TS       TIMESTAMP,
    LAST_UPDATED_TS  TIMESTAMP       NOT NULL,
    CONSTRAINT PK_DEMO_PAYMENTS PRIMARY KEY (PAYMENT_ID)
);

CREATE TABLE DEMO_INVENTORY (
    WAREHOUSE_ID     NUMBER(6)       NOT NULL,
    PRODUCT_ID       NUMBER(12)      NOT NULL,
    ON_HAND_QTY      NUMBER(12,2),
    RESERVED_QTY     NUMBER(12,2),
    LAST_UPDATED_TS  TIMESTAMP       NOT NULL,
    CONSTRAINT PK_DEMO_INVENTORY PRIMARY KEY (WAREHOUSE_ID, PRODUCT_ID)
);

